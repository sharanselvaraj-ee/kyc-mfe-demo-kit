// SLIDE: "Two cadences, one architecture: shell and slot" (the build-time lite manifest, LITE-001)
import { writeFile } from "node:fs/promises";
import { gbFeatures, inFeatures, aeFeatures, sgFeatures } from "@kyc/mocks";

const ALL = { GB: gbFeatures, IN: inFeatures, AE: aeFeatures, SG: sgFeatures };
const liteGeos = Object.entries(ALL)
  .filter(([, features]) => features.flags["kyc.lite.available"])
  .map(([geo]) => geo);

const path = new URL("../src/lite-manifest.generated.ts", import.meta.url);
await writeFile(
  path,
  `// GENERATED by packages/loader/scripts/generate-manifest.mjs from the geo fixtures' kyc.lite.available flag.\n` +
    `// Regenerate with: pnpm --filter @kyc/loader generate-manifest\n` +
    `export const LITE_AVAILABLE_GEOS: readonly string[] = ${JSON.stringify(liteGeos)};\n`,
);
console.log(`[loader] wrote lite manifest: ${liteGeos.join(", ")}`);
