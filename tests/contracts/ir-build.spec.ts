// SLIDE: "Agents author IR, compilers emit code" (IR-001: written once, compiled twice)
import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, it, expect } from "vitest";

const ROOT = join(import.meta.dirname, "../..");
const IR_DIR = join(ROOT, "packages/ir/src");
const REACT_DIR = join(ROOT, "packages/gen/react/src");
const SVELTE_DIR = join(ROOT, "packages/gen/svelte/src");

function baseNames(dir: string, ext: string): string[] {
  return readdirSync(dir)
    .filter((f) => f.endsWith(ext))
    .map((f) => f.slice(0, -ext.length));
}

describe("Mitosis build output", () => {
  const irNames = baseNames(IR_DIR, ".lite.tsx").sort();
  const reactNames = baseNames(REACT_DIR, ".jsx").sort();
  const svelteNames = baseNames(SVELTE_DIR, ".svelte").sort();

  it("[IR-001] every IR primitive produced both a React and a Svelte component", () => {
    expect(reactNames).toEqual(irNames);
    expect(svelteNames).toEqual(irNames);
  });

  it("[IR-001] every generated file carries the required GENERATED header", () => {
    for (const name of reactNames) {
      const content = readFileSync(join(REACT_DIR, `${name}.jsx`), "utf8");
      expect(content).toMatch(new RegExp(`^// GENERATED by Mitosis from packages/ir/${name}\\.lite\\.tsx`));
    }
    for (const name of svelteNames) {
      const content = readFileSync(join(SVELTE_DIR, `${name}.svelte`), "utf8");
      expect(content).toMatch(new RegExp(`^<!-- GENERATED by Mitosis from packages/ir/${name}\\.lite\\.tsx`));
    }
  });
});
